'''
Operadores de atribuição
= += -= *= /= //= **= %=

Usa o valor antigo e faz a operação desejada

'''
contador = 0
# contador = contador + 1
# print(contador)

contador += 1 # valor antigo de contador (0) + 1 = 1
print(contador)

contador = 2
contador *= 3 # valor antigo de contador (2) * 3 = 6
print(contador)

contador = 5
contador **= 2 # 5 elevado a 2 = 25
print(contador)